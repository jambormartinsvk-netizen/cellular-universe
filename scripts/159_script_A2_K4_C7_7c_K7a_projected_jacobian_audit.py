        '            frozen_projected = T@physical_jacobian@Tinv\n'
        '            connection = Tp@Tinv\n'
        '            transformed_projected = frozen_projected + connection\n'
        '            def transformation_at(x_value):\n'
        '                local_bg = background(x_value)\n'
        '                local_Og = local_bg["Omega_gamma"]\n'
        '                local_On = local_bg["Omega_fs"]\n'
        '                local_Ob = local_bg["Omega_b"]\n'
        '                local_Oc = local_bg["Omega_c"]\n'
        '                local_Of = local_bg["Omega_f"]\n'
        '                local_T = np.eye(len(STATE_NAMES))\n'
        '                local_T[3, :] = 0.0\n'
        '                local_T[3, 2] = local_Og\n'
        '                local_T[3, 3] = local_On\n'
        '                local_T[3, 4] = local_Ob\n'
        '                local_T[3, 5] = local_Oc\n'
