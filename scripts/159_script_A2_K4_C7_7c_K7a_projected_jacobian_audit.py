        '                (\n'
        '                    hp, etap, dgp, Dp, dbp, dcp, Ugp, Mp,\n'
        '                    sigp, L3p, L4p, dfp, Ufp,\n'
        '                ) = projected_state\n'
        '                dnp = (\n'
