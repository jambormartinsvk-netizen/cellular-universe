        '                np.zeros(len(STATE_NAMES))\n'
        '            )\n'
        '            for projected_column in range(len(STATE_NAMES)):\n'
        '                projected_basis = np.zeros(len(STATE_NAMES))\n'
        '                projected_basis[projected_column] = 1.0\n'
        '                projected_explicit[:, projected_column] = (\n'
        '                    explicit_projected_rhs(projected_basis)-projected_zero\n'
